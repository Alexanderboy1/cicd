/**
 * lint-staged 配置文件
 * ---------------------------------------------------------------
 * 作用：在 git commit 时，只对「本次暂存（git add 过）的文件」执行检查，
 *      而不是检查整个项目。这样速度快，也不会因为别人的旧代码报错而挡住你提交。
 *
 * 它由 .husky/pre-commit 这个钩子来触发调用。
 *
 * 配置格式：{ "文件匹配规则": "要执行的命令" }
 *   - key（键）：用 glob 通配符匹配文件，例如 *.ts 表示所有 .ts 文件
 *   - value（值）：匹配到文件后要跑的命令，可以是一个字符串，也可以是数组（多条命令）
 * ---------------------------------------------------------------
 */
export default {
  // 匹配所有 .js / .jsx / .ts / .tsx 源码文件
  // 对这些暂存文件执行 eslint 检查：
  //   --fix           ：能自动修复的问题（比如缺分号、格式）就自动修好
  //   --max-warnings=0：只要有一个 warning（警告）也算失败，从而阻止提交
  // 如果 eslint 报错，commit 会被中断，你需要修好后重新提交。
  '*.{js,jsx,ts,tsx}': ['eslint --fix --max-warnings=0'],
}
